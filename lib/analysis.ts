export function analyzeThreatCase(input: string): AnalysisResult {
  const normalized = input.trim().toLowerCase();

  if (!normalized) {
    return fallbackResult;
  }

  const preset = analyzerPresets.find(({ keywords }) =>
    keywords.some((keyword) => normalized.includes(keyword)),
  );

  if (!preset) {
    return fallbackResult;
  }

  return {
    title: preset.result.title,
    threatType: preset.result.threatType,
    severity: preset.result.severity,
    needsExpert: preset.result.needsExpert,
    summary: preset.result.summaryTemplate,
    firstSteps: preset.result.firstSteps,
    recommendations: preset.result.recommendations,
  };
}
